def _normalize_label(s: str) -> str | None:
    s = (s or "").strip().lower()
    if s == "yes":
        return "Yes"
    if s == "no":
        return "No"
    return None

def _parse_raw(raw: str) -> list[str]:
    labels = []
    for ln in (raw or "").splitlines():
        lab = _normalize_label(ln)
        if lab is not None:
            labels.append(lab)
    return labels

